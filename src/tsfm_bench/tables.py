def frontier_table() -> str:
    """Accuracy against per-series history length."""
    s = _read("study2_summary.csv")
    for c in ("T", "mean_mase"):
        s[c] = pd.to_numeric(s[c], errors="coerce")
    models = ["AutoETS"] + [m for m in FM_ORDER if m in set(s["model"])]
    datasets = [d for d in ("M4-Monthly", "M4-Quarterly", "M5-daily")
                if d in set(s["dataset"])]
    shown = {"M4-Monthly": [12, 48, 96, 384], "M4-Quarterly": [8, 16, 128],
             "M5-daily": [28, 224]}

    hdr = "$T$ & " + " & ".join(_short(m) for m in models) + NL + MID
    rows = ""
    for ds in datasets:
        rows += ("\\multicolumn{" + str(len(models) + 1) + "}{l}{\\emph{" + ds + "}}" + NL)
        piv = s[s["dataset"] == ds].pivot_table(index="T", columns="model",
                                                values="mean_mase")
        for T in [t for t in shown.get(ds, list(piv.index)) if t in piv.index]:
            vals = {m: piv.loc[T].get(m) for m in models}
            fin = {k: float(v) for k, v in vals.items()
                   if v is not None and np.isfinite(v)}
            best = min(fin, key=fin.get) if fin else None
            cells = [("\\textbf{" + _fmt(v, 3) + "}") if k == best else _fmt(v, 3)
                     for k, v in vals.items()]
            rows += f"{int(T)} & " + " & ".join(cells) + NL
        if ds != datasets[-1]:
            rows += MID
    cap = ("Mean MASE against per-series history $T$ (best per row in bold), five "
           "foundation models and a ten-parameter AutoETS, over eight rolling origins. "
           "On the smooth M4 data the winner permutes with both $T$ and model choice and "
           "AutoETS lies inside the spread of the foundation models; on "
           "intermittent M5 every foundation model beats AutoETS decisively. Requiring "
           "eight origins restricts the sample to longer series, so these figures are not "
           "directly comparable with three-origin studies.")
    cap += " " + ABBREV_NOTE
    return _wrap(hdr + rows, cap, "tab:frontier", "l" + "r" * len(models), "4.5pt")


# --------------------------------------------------------------------------- #
def write_all() -> list:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    written = []
    for fn, name in [(coherence_table, "coherence"), (temporal_table, "temporal"),
                     (nonneg_table, "nonneg"), (recon_table, "recon"),
                     (probcoh_table, "probcoh"), (frontier_table, "frontier")]:
        try:
            (TABLE_DIR / f"{name}.tex").write_text(fn())
            written.append(name)
        except Exception as e:
            print(f"  [fail] {name}: {type(e).__name__}: {e}")
    return written
