def coherence_table() -> str:
    df = _read("coherence_incoherence.csv")
    piv = df.pivot_table(index="group", columns="model", values="pct_nodes_incoherent")
    fms = [m for m in FM_ORDER if m in piv.columns]
    classical = ["AutoETS"] if "AutoETS" in piv.columns else []
    globals_ = [m for m in GLOBAL_ORDER if m in piv.columns]
    models = fms + classical + globals_
    groups = [g for g in HIER_ORDER if g in piv.index]

    naggs = {}
    for g in groups:
        try:
            from .coherence import load_hierarchy
            _Y, S, _t, _m = load_hierarchy(g)
            naggs[g] = S.shape[0] - S.shape[1]
        except Exception:
            naggs[g] = None

    # Group header banding: foundation models | classical | trained global.
    banner = "\\multicolumn{1}{c}{} & " \
        + f"\\multicolumn{{{len(fms)}}}{{c}}{{foundation (zero-shot)}}"
    if classical:
        banner += f" & \\multicolumn{{{len(classical)}}}{{c}}{{classical}}"
    if globals_:
        banner += f" & \\multicolumn{{{len(globals_)}}}{{c}}{{trained global}}"
    banner += NL
    hdr = (banner + "Hierarchy (agg.) & "
           + " & ".join(_short(m) for m in models) + NL + MID)
    rows = ""
    for g in groups:
        n = naggs.get(g)
        label = f"{HIER_LABEL.get(g, g)} (${n}$)" if n else HIER_LABEL.get(g, g)
        rows += label + " & " + " & ".join(_fmt(piv.loc[g].get(m)) for m in models) + NL

    # Narrative numbers, derived so the caption cannot drift from the data.
    fm_piv = piv.loc[groups, fms]
    # A hierarchy is "mostly incoherent" if the median foundation model exceeds 50%.
    med = fm_piv.median(axis=1)
    mostly = [g for g in groups if med[g] > 50]
    exceptions = [HIER_LABEL.get(g, g) for g in groups if med[g] <= 50]
    lo_mostly = float(fm_piv.loc[mostly].min().min())
    glob_lo = float(piv.loc[groups, globals_].min().min()) if globals_ else None
    glob_hi = float(piv.loc[groups, globals_].max().max()) if globals_ else None
    cap = ("Percentage of aggregate nodes that are incoherent (children do not sum to "
           "the parent, relative gap $>1\\%$), averaged over up to eight rolling origins. "
           f"On {len(mostly)} of the {len(groups)} hierarchies the median foundation "
           "model is incoherent on most aggregate nodes; the two exceptions "
           f"({' and '.join(exceptions)}) are the hierarchies whose aggregates are "
           "dominated by a common smooth component, which independent forecasts "
           "reproduce almost exactly. Incoherence does not track model capacity "
           "($0.8$M--$200$M parameters, a factor of $250$): the low values belong to "
           "TinyTimeMixer, the smallest and least accurate model, where a flat forecast "
           "is trivially closer to coherent. The classical AutoETS is incoherent at the "
           "same rates, and the two trained global models, which forecast every "
           f"node jointly rather than per series, are incoherent on ${glob_lo:.0f}$--"
           f"${glob_hi:.0f}\\%$ of nodes, so the failure is not specific to per-series "
           "forecasting but general to any model whose outputs are not projected onto the "
           "coupling set. Bottom-up reconciliation drives all of these to exactly zero.")
    cap += " " + ABBREV_NOTE
    # Nine model columns do not fit elsarticle's default review text block at
    # \small; footnotesize, a tight column gap and a final scale-to-width keep
    # it inside the margins.
    return _wrap(hdr + rows, cap, "tab:coherence", "l" + "r" * len(models),
                 "2pt", fontsize="footnotesize", fit_width=True)


