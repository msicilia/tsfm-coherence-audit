def temporal_table() -> str:
    df = _read("temporal_coherence_summary.csv")
    piv = df.pivot_table(index="model", columns="k", values="pct_nodes_incoherent")
    ks = sorted(piv.columns)
    models = [m for m in FM_ORDER if m in piv.index]
    hdr = ("& \\multicolumn{" + str(len(ks)) +
           "}{c}{aggregation factor $k$ (months per block)}" + NL
           + f"\\cmidrule(lr){{2-{len(ks) + 1}}}\n"
           + "Model & " + " & ".join(f"${k}$" for k in ks) + NL + MID)
    rows = "".join(_short(m) + " & " + " & ".join(_fmt(piv.loc[m, k]) for k in ks) + NL
                   for m in models)
    cap = ("Temporal incoherence: percentage of aggregate nodes at which a model's "
           "directly forecast aggregate differs by more than $1\\%$ from the sum of its "
           "own monthly forecasts of the same series. $400$ M4-Monthly series, four "
           "rolling origins.")
    cap += _abbrev_note(models)
    return _wrap(hdr + rows, cap, "tab:temporal", "l" + "r" * len(ks))


