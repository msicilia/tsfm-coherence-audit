def recon_table() -> str:
    """Accuracy of restoring coherence, and what the best coherent option actually is."""
    df = _read("coherence_accuracy.csv")
    piv = df.pivot_table(index="group", columns=["model", "method"], values="mase")
    # ERM stability flag (learned reconciler is under-determined on small hierarchies).
    erm = df[df["method"] == "ERM"]
    erm_stable = {(r["model"], r["group"]): bool(r["stable"]) for _, r in erm.iterrows()}
    groups = [g for g in HIER_ORDER if g in piv.index]
    show = [m for m in ("Chronos-2", "TimesFM") if (m, "raw") in piv.columns]
    erm_model = "Chronos-2"

    def coherent_options(g):
        opts = {}
        for m in piv.columns.get_level_values(0).unique():
            if (m, "BottomUp") in piv.columns:
                v = piv.loc[g].get((m, "BottomUp"))
                if v is not None and np.isfinite(v):
                    opts[m] = float(v)
        caa = piv.loc[g].get(("CAA", "reconciled"))
        if caa is not None and np.isfinite(caa):
            opts["CAA"] = float(caa)
        return opts

    hdr = ("& " + " & ".join("\\multicolumn{2}{c}{" + m + "}" for m in show)
           + " & C-2 ERM & CAA & best" + NL
           + "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(show)))
           + "\n" + "Hierarchy & " + " & ".join("raw & +\\,b.u." for _ in show)
           + " & +\\,ERM & (coh.) & coherent" + NL + MID)

    rows = ""
    for g in groups:
        cells = []
        for m in show:
            cells += [_fmt(piv.loc[g].get((m, "raw")), 3),
                      _fmt(piv.loc[g].get((m, "BottomUp")), 3)]
        # ERM cell: value where numerically stable, otherwise flagged unstable.
        if erm_stable.get((erm_model, g), False):
            erm_cell = _fmt(piv.loc[g].get((erm_model, "ERM")), 3)
        else:
            erm_cell = "unst."
        caa = piv.loc[g].get(("CAA", "reconciled"))
        opts = coherent_options(g)
        best = min(opts.values()) if opts else None
        rows += (HIER_LABEL.get(g, g) + " & " + " & ".join(cells)
                 + f" & {erm_cell} & {_fmt(caa, 3)} & {_fmt(best, 3)}" + NL)

    cap = ("Mean MASE (up to eight rolling origins) of the raw and the bottom-up "
           "reconciled (``+\\,b.u.'') forecasts of two foundation models, of Chronos-2 "
           "reconciled by ERM (``unst.'' where the reconciler diverged), of CAA, and of "
           "the best coherent option over every bottom-up reconciled model and CAA.")
    return _wrap(hdr + rows, cap, "tab:recon", "l" + "rr" * len(show) + "rrr")


