def probcoh_table() -> str:
    """Distributional coherence: raw vs three reconciliations, ordered by dependence."""
    df = _read("prob_coherence.csv")
    agg = df[~df["is_bottom"]]
    g = (agg.groupby(["model", "group"])
         .agg(dep=("dependence", "mean"), raw=("crps_raw", "mean"),
              indep=("crps_indep", "mean"), schaake=("crps_schaake", "mean"),
              gauss=("crps_gauss", "mean")).reset_index())

    show = [m for m in ("Chronos-2", "TimesFM") if m in set(g["model"])]
    hdr = ("& & dep. & raw & \\multicolumn{3}{c}{coherent}" + NL
           + "\\cmidrule(lr){5-7}\n"
           + "Model & Hierarchy & $\\bar\\rho$ & (incoh.) & indep. & Schaake & Gauss."
           + NL + MID)
    rows = ""
    for i, m in enumerate(show):
        sub = g[g["model"] == m].sort_values("dep")
        for j, (_, r) in enumerate(sub.iterrows()):
            lead = m if j == 0 else ""
            rows += (f"{lead} & {HIER_LABEL.get(r['group'], r['group'])} & "
                     f"{_fmt(r['dep'], 2)} & {_fmt(r['raw'], 3)} & {_fmt(r['indep'], 3)} & "
                     f"{_fmt(r['schaake'], 3)} & {_fmt(r['gauss'], 3)}" + NL)
        if i < len(show) - 1:
            rows += MID
    n_models = int(g["model"].nunique())
    cap = ("Probabilistic coherence (mean scaled CRPS at aggregate nodes, up to eight "
           "rolling origins), ordered by hierarchy dependence $\\bar\\rho$ (mean "
           "$|$correlation$|$ of the bottom series). Raw (incoherent) predictive "
           "distribution versus three coherent sample-space reconciliations: summing "
           "independent marginals, and summing after a Schaake shuffle or a fitted "
           "Gaussian copula. Summing independent marginals is close to cost-free on most "
           "hierarchies and expensive only on Traffic; the copula couplings recover that "
           "cost and, on the strongly dependent hierarchies, improve on the raw "
           f"distribution. The pattern holds for all {n_models} models that emit "
           "quantiles (two shown; full table in the released results).")
    return _wrap(hdr + rows, cap, "tab:probcoh", "llrrrrr")


