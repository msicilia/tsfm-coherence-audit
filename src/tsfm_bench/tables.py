_FREQ = {"D": "daily", "MS": "monthly", "M": "monthly", "Q": "quarterly", "H": "hourly"}
# Sampling frequency of the hierarchies we build ourselves (no `freq` in their meta).
_FREQ_BUILT = {"M5": "daily", "Electricity": "hourly", "Solar": "hourly"}


def datasets_table() -> str:
    """Every dataset the paper uses, its size, horizon, origins and the study it serves.

    Sizes come from the loaders and the result CSVs, so the table cannot drift from
    what was run. The non-hierarchical datasets appear once per study because each
    study takes a different subset.
    """
    from .hierarchies import load as load_hierarchy
    inc = _read("coherence_incoherence.csv")
    nwin = inc.groupby("group")["n_windows"].max()
    dep = _read("prob_law_points.csv").groupby("group")["dependence"].mean()

    rows = ""
    for g in HIER_ORDER:
        _Y, S, _t, meta = load_hierarchy(g)
        n_tot, n_bot = S.shape
        freq = _FREQ_BUILT.get(g) or _FREQ.get(getattr(meta, "freq", None), "---")
        rows += (f"{HIER_LABEL.get(g, g)} & {freq} & {n_tot} & {n_bot} & {n_tot - n_bot} & "
                 f"{meta.horizon} & {int(nwin.get(g, 0))} & {_fmt(dep.get(g), 2)} & "
                 "\\ref{sec:coherence}--\\ref{sec:probcoh}" + NL)
    rows += MID

    # Non-hierarchical datasets: series counts from the result files of each study.
    fr = _read("study2_raw.csv")
    n_fr = fr.groupby("dataset")["uid"].nunique()
    fr_h = {"M4-Monthly": 18, "M4-Quarterly": 8, "M5-daily": 14}
    fr_w = int(fr.groupby("dataset")["window"].nunique().max())
    for ds, label in [("M4-Monthly", "M4 monthly"), ("M4-Quarterly", "M4 quarterly"),
                      ("M5-daily", "M5 daily")]:
        rows += (f"{label} & {ds.split('-')[1].lower()} & {int(n_fr.get(ds, 0))} & --- & --- & "
                 f"{fr_h[ds]} & {fr_w} & --- & \\ref{{sec:frontier}}" + NL)
    tmp = _read("temporal_coherence_raw.csv")
    rows += (f"M4 monthly & monthly & {tmp['uid'].nunique()} & --- & --- & 12 & "
             f"{tmp['window'].nunique()} & --- & \\ref{{sec:temporal}}" + NL)
    # Non-negativity: the loaders' deterministic samples (cap 1200), as in run_all.
    try:
        from .loaders import load_m3, load_m5_sample
        n_m3 = sum(len(it.y) > 12 + 4 for it in load_m3("Monthly", max_series=1200))
        n_m5 = sum(len(it.y) > 28 + 4 for it in load_m5_sample(n_series=1200, min_len=200))
    except Exception:
        n_m3 = n_m5 = None
    rows += (f"M3 monthly & monthly & {n_m3 if n_m3 else '---'} & --- & --- & 12 & 1 & --- & "
             "\\ref{sec:nonneg}" + NL)
    rows += (f"M5 daily & daily & {n_m5 if n_m5 else '---'} & --- & --- & 28 & 1 & --- & "
             "\\ref{sec:nonneg}" + NL)
    abl = _read("caaa_ablation_summary.csv")
    rows += (f"M4 monthly (capacity) & monthly & {int(abl['n'].max())} & --- & --- & 18 & 1 & "
             "--- & \\ref{sec:frontier}" + NL)

    hdr = ("Dataset & Freq. & Series & Bottom & Aggr. & $h$ & Origins & $\\bar\\rho$ & Section"
           + NL + MID)
    cap = ("Datasets used in each study. For the eight hierarchies (top), Series is the "
           "number of nodes, split into bottom and aggregate nodes; $h$ is the forecast "
           "horizon, Origins the number of rolling origins, and $\\bar\\rho$ the "
           "cross-series dependence (mean $|$correlation$|$ of the bottom series' first "
           "differences). The non-hierarchical datasets (bottom) are listed once per study "
           "with the number of series that study used.")
    return _wrap(hdr + rows, cap, "tab:datasets", "llrrrrrrl", "3pt",
                 fontsize="footnotesize")


