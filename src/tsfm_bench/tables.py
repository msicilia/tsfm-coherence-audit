def frontier_table() -> str:
    """Accuracy against per-series history length."""
    s = _read("study2_summary.csv")
    for c in ("T", "mean_mase"):
        s[c] = pd.to_numeric(s[c], errors="coerce")
    models = ["AutoETS"] + [m for m in FM_ORDER if m in set(s["model"])]
    datasets = [d for d in ("M4-Monthly", "M4-Quarterly", "M5-daily")
                if d in set(s["dataset"])]
    shown = {"M4-Monthly": [12, 48, 96, 384], "M4-Quarterly": [8, 16, 128],
             "M5-daily": [28, 224]}

    hdr = "$T$ & " + " & ".join(_short(m) for m in models) + NL + MID
    rows = ""
    for ds in datasets:
        rows += ("\\multicolumn{" + str(len(models) + 1) + "}{l}{\\emph{" + ds + "}}" + NL)
        piv = s[s["dataset"] == ds].pivot_table(index="T", columns="model",
                                                values="mean_mase")
        for T in [t for t in shown.get(ds, list(piv.index)) if t in piv.index]:
            vals = {m: piv.loc[T].get(m) for m in models}
            fin = {k: float(v) for k, v in vals.items()
                   if v is not None and np.isfinite(v)}
            best = min(fin, key=fin.get) if fin else None
            cells = [("\\textbf{" + _fmt(v, 3) + "}") if k == best else _fmt(v, 3)
                     for k, v in vals.items()]
            rows += f"{int(T)} & " + " & ".join(cells) + NL
        if ds != datasets[-1]:
            rows += MID
    cap = ("Mean MASE against per-series history $T$ (best per row in bold) over eight "
           "rolling origins, five foundation models and AutoETS. Requiring eight origins "
           "restricts the sample to longer series.")
    cap += _abbrev_note(models)
    return _wrap(hdr + rows, cap, "tab:frontier", "l" + "r" * len(models), "4.5pt")


