def probcoh_table() -> str:
    """Distributional coherence: raw vs three reconciliations, ordered by dependence."""
    df = _read("prob_coherence.csv")
    agg = df[~df["is_bottom"]]
    g = (agg.groupby(["model", "group"])
         .agg(dep=("dependence", "mean"), raw=("crps_raw", "mean"),
              indep=("crps_indep", "mean"), schaake=("crps_schaake", "mean"),
              gauss=("crps_gauss", "mean")).reset_index())

    show = [m for m in ("Chronos-2", "TimesFM") if m in set(g["model"])]
    hdr = ("& & dep. & raw & \\multicolumn{3}{c}{coherent}" + NL
           + "\\cmidrule(lr){5-7}\n"
           + "Model & Hierarchy & $\\bar\\rho$ & (incoh.) & indep. & Schaake & Gauss."
           + NL + MID)
    rows = ""
    for i, m in enumerate(show):
        sub = g[g["model"] == m].sort_values("dep")
        for j, (_, r) in enumerate(sub.iterrows()):
            lead = m if j == 0 else ""
            rows += (f"{lead} & {HIER_LABEL.get(r['group'], r['group'])} & "
                     f"{_fmt(r['dep'], 2)} & {_fmt(r['raw'], 3)} & {_fmt(r['indep'], 3)} & "
                     f"{_fmt(r['schaake'], 3)} & {_fmt(r['gauss'], 3)}" + NL)
        if i < len(show) - 1:
            rows += MID
    n_models = int(g["model"].nunique())
    cap = ("Mean scaled CRPS at aggregate nodes (up to eight rolling origins) of the raw "
           "predictive distribution and of three coherent reconciliations in sample space "
           "(independent summation, Schaake shuffle, Gaussian copula), ordered by "
           "hierarchy dependence $\\bar\\rho$ (mean $|$correlation$|$ of the bottom "
           f"series). Two of the {n_models} quantile-emitting models are shown; the full "
           "table is in the released results.")
    return _wrap(hdr + rows, cap, "tab:probcoh", "llrrrrr")


