def nonneg_table() -> str:
    df = _read("nonneg_summary.csv")
    piv = df.pivot_table(index="model", columns="dataset",
                         values=["pct_median_below0", "pct_lower_below0"])
    ds = [d for d in ("M5-daily", "M3-Monthly") if d in df["dataset"].unique()]
    order = sorted(piv.index,
                   key=lambda m: -float(piv[("pct_median_below0", ds[0])].get(m, 0)))
    hdr = ("& \\multicolumn{2}{c}{M5 retail (near zero)} & "
           "\\multicolumn{2}{c}{M3 (far from zero)}" + NL
           + "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n"
           + "Model & median $<0$ & band $<0$ & median $<0$ & band $<0$" + NL + MID)
    rows = ""
    for m in order:
        vals = [piv[("pct_median_below0", ds[0])].get(m),
                piv[("pct_lower_below0", ds[0])].get(m),
                piv[("pct_median_below0", ds[-1])].get(m),
                piv[("pct_lower_below0", ds[-1])].get(m)]
        rows += _short(m) + " & " + " & ".join(_fmt(v) for v in vals) + NL
    cap = ("Non-negativity violations: percentage of strictly non-negative series on "
           "which a zero-shot forecast goes below zero, for the median forecast and the "
           "lower ($10\\%$) predictive band. Violations appear only where the data sits "
           "against the boundary (M5 retail counts), and are essentially absent far from "
           "it (M3).")
    cap += " " + ABBREV_NOTE
    return _wrap(hdr + rows, cap, "tab:nonneg", "lrrrr")


