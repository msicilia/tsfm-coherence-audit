def timing_table() -> str:
    """Wall-clock cost of each step on one rolling origin per hierarchy."""
    df = _read("timing.csv")
    base = "Chronos-2"
    piv = df[df["model"].isin([base, "---"])].pivot_table(
        index="group", columns="step", values="seconds", aggfunc="sum")
    n = df.drop_duplicates("group").set_index("group")[["n_nodes"]]
    cols = [("inference", "inference"), ("BottomUp", "b.u."), ("MinT-ols", "MinT-ols"),
            ("MinT-shrink", "MinT-shr."), ("ERM", "ERM"), ("quantiles+samples", "sampl."),
            ("indep", "indep."), ("Schaake", "Schaake"), ("Gaussian", "Gauss.")]
    cols = [c for c in cols if c[0] in piv.columns]

    def _t(x):
        if x is None or not np.isfinite(x):
            return "---"
        return "$<0.01$" if x < 0.005 else (f"{x:.2f}" if x < 10 else f"{x:.0f}")

    hdr = ("& & \\multicolumn{1}{c}{base} & \\multicolumn{4}{c}{point reconciliation} & "
           "\\multicolumn{4}{c}{probabilistic}" + NL
           + "\\cmidrule(lr){3-3}\\cmidrule(lr){4-7}\\cmidrule(lr){8-11}\n"
           + "Hierarchy & nodes & " + " & ".join(c[1] for c in cols) + NL + MID)
    rows = ""
    for g in HIER_ORDER:
        if g not in piv.index:
            continue
        rows += (f"{HIER_LABEL.get(g, g)} & {int(n.loc[g, 'n_nodes'])} & "
                 + " & ".join(_t(piv.loc[g].get(c[0])) for c in cols) + NL)
    cap = ("Wall-clock seconds of each step for Chronos-2 on one rolling origin per "
           "hierarchy (all nodes). Inference is the zero-shot point forecast on the GPU; "
           "ERM includes the in-sample forecast passes its fit requires; sampl.\\ is the "
           "quantile forecast and the draw of $200$ samples per node; indep., Schaake and "
           "Gauss.\\ are the three sample-space reconciliations. Reconciliation and "
           "coupling run on the CPU.")
    return _wrap(hdr + rows, cap, "tab:timing", "lr" + "r" * len(cols), "2.5pt",
                 fontsize="footnotesize", fit_width=True)


def inference_timing_table() -> str:
    """Zero-shot inference seconds per model and hierarchy, plus peak GPU memory."""
    df = _read("timing.csv")
    inf = df[df["step"] == "inference"]
    sec = inf.pivot_table(index="group", columns="model", values="seconds")
    mem = inf.pivot_table(index="group", columns="model", values="gpu_peak_mb")
    meta = df.drop_duplicates("group").set_index("group")[["n_nodes", "h"]]
    models = [m for m in FM_ORDER if m in sec.columns]

    def _t(x):
        if x is None or not np.isfinite(x):
            return "---"
        return "$<0.01$" if x < 0.005 else (f"{x:.2f}" if x < 10 else f"{x:.0f}")

    hdr = ("Hierarchy & nodes & " + " & ".join(_short(m) for m in models) + NL + MID)
    rows = ""
    for g in HIER_ORDER:
        if g not in sec.index:
            continue
        rows += (f"{HIER_LABEL.get(g, g)} & {int(meta.loc[g, 'n_nodes'])} & "
                 + " & ".join(_t(sec.loc[g].get(m)) for m in models) + NL)
    rows += MID + ("Peak GPU GB & & "
                   + " & ".join(f"{mem[m].max() / 1024:.1f}" for m in models) + NL)
    cap = ("Wall-clock seconds of zero-shot point inference for every node of each "
           "hierarchy on one rolling origin (GPU, batches of $256$ series, after a "
           "warm-up call). The last row is the peak GPU memory allocated during the "
           "call, in GB, with all six models resident." + _abbrev_note(models))
    return _wrap(hdr + rows, cap, "tab:inftiming", "lr" + "r" * len(models), "3pt",
                 fontsize="footnotesize")


# --------------------------------------------------------------------------- #
def write_all() -> list:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    written = []
    for fn, name in [(coherence_table, "coherence"), (temporal_table, "temporal"),
                     (nonneg_table, "nonneg"), (recon_table, "recon"),
                     (probcoh_table, "probcoh"), (frontier_table, "frontier"),
                     (datasets_table, "datasets"), (timing_table, "timing"),
                     (inference_timing_table, "inference_timing")]:
        try:
            (TABLE_DIR / f"{name}.tex").write_text(fn())
            written.append(name)
        except Exception as e:
            print(f"  [fail] {name}: {type(e).__name__}: {e}")
    return written
