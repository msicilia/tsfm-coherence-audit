"""Generate the paper's LaTeX tables directly from result CSVs.

Each table is emitted as a standalone `.tex` fragment that `main.tex` inputs, so the
numbers in the manuscript cannot drift from the numbers in the result CSVs.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from .paths import PAPER, RESULTS

TABLE_DIR = PAPER / "tables"

# Older result files carry the pre-rename label for the assembly method.
MODEL_ALIASES = {"CAAA": "CAA"}

FM_ORDER = ["TinyTimeMixer", "Chronos-Bolt", "Chronos-Bolt-Base", "Chronos-2",
            "Moirai", "TimesFM"]
GLOBAL_ORDER = ["LightGBM", "TCN"]           # trained global (non-zero-shot) baselines
# Hierarchies in ascending cross-series dependence (bottom-series mean |corr|).
HIER_ORDER = ["Wiki2", "TourismLarge", "Labour", "TourismSmall", "M5", "Traffic",
              "Electricity", "Solar"]
HIER_LABEL = {"M5": "M5 retail"}

NL = " \\\\\n"          # LaTeX row terminator
MID = "\\midrule\n"


def _read(name: str) -> pd.DataFrame:
    df = pd.read_csv(RESULTS / name)
    if "model" in df.columns:
        df["model"] = df["model"].replace(MODEL_ALIASES)
    return df


def _fmt(x, nd=1):
    if x is None:
        return "---"
    try:
        x = float(x)
    except (TypeError, ValueError):
        return "---"
    return "---" if not np.isfinite(x) else f"{x:.{nd}f}"


ABBREV = {"TinyTimeMixer": "TTM", "Chronos-Bolt": "C-Bolt",
          "Chronos-Bolt-Base": "C-Bolt-B", "Chronos-2": "C-2",
          "LightGBM": "LGBM"}
ABBREV_NOTE = ("TTM = TinyTimeMixer; C-Bolt = Chronos-Bolt; "
               "C-Bolt-B = Chronos-Bolt-Base; C-2 = Chronos-2; LGBM = LightGBM.")


def _short(m: str) -> str:
    """Compact column headers; the full names overrun the text block."""
    return ABBREV.get(m, m)


def _wrap(body: str, caption: str, label: str, colspec: str,
          tabcolsep: str | None = None, fontsize: str = "small",
          fit_width: bool = False) -> str:
    """Emit a booktabs table. `fit_width` scales the tabular down to the text
    block for tables too wide to fit otherwise; it stays selectable text."""
    sep = f"\\setlength{{\\tabcolsep}}{{{tabcolsep}}}\n" if tabcolsep else ""
    open_, close = ("\\resizebox{\\linewidth}{!}{%\n", "}\n") if fit_width else ("", "")
    return ("% AUTO-GENERATED by tsfm_bench.tables. Do not edit by hand.\n"
            "\\begin{table}[t]\n\\centering\n" + f"\\{fontsize}\n" + sep + open_
            + f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{body}\\bottomrule\n"
            + "\\end{tabular}\n" + close
            + f"\\caption{{{caption}}}\n\\label{{{label}}}\n"
            + "\\end{table}\n")


